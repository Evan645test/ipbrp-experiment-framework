#!/usr/bin/env node
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";

const source = JSON.parse(await readFile(new URL("../public/data/paper-01.json", import.meta.url), "utf8"));
const baseline = JSON.parse(await readFile(new URL("../content/paper-01-before-order-repair.json", import.meta.url), "utf8")).paper;
const text = await readFile(new URL("../lib/curator-state.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(text, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { loadCuratorDraft, curatorStorageKey } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const storage = new Map();
globalThis.window = { localStorage: { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) } };
const key = curatorStorageKey(source.id);
const local = structuredClone(baseline);
local.segments[1].translation.plainZh = "preserved translation edit";
storage.set(key, JSON.stringify(local));
const migrated = loadCuratorDraft(source);
assert.deepEqual(migrated.segments.map(s => s.id), source.segments.map(s => s.id));
assert.equal(migrated.segments.find(s => s.id === local.segments[1].id).translation.plainZh, "preserved translation edit");
assert.equal(migrated.segments.find(s => s.id === "paper-01-s-fb4b491173bb").excluded, true);
assert.equal(migrated.segments.filter(s => !s.excluded).length, source.segments.filter(s => !s.excluded).length);

const custom = structuredClone(local);
[custom.segments[10], custom.segments[11]] = [custom.segments[11], custom.segments[10]];
custom.segments.at(-1).excluded = false;
storage.set(key, JSON.stringify(custom));
const preserved = loadCuratorDraft(source);
const previousIds = new Set(baseline.segments.map(s => s.id));
assert.deepEqual(preserved.segments.filter(s => previousIds.has(s.id)).map(s => s.id), custom.segments.map(s => s.id));
assert.equal(preserved.segments.length, source.segments.length);
assert.equal(preserved.segments.find(s => s.id === custom.segments.at(-1).id).excluded, false);

const afterReview = structuredClone(migrated);
[afterReview.segments[1], afterReview.segments[2]] = [afterReview.segments[2], afterReview.segments[1]];
storage.set(key, JSON.stringify(afterReview));
assert.deepEqual(loadCuratorDraft(source).segments.map(s => s.id), afterReview.segments.map(s => s.id));

const deleted = structuredClone(custom);
deleted.segments.splice(10, 1);
storage.set(key, JSON.stringify(deleted));
assert.equal(loadCuratorDraft(source).segments.length, source.segments.length - 1);
console.log("Curator order repair: stale drafts, local translations, explicit exclusions, custom ordering, one-time migration and intentional deletions passed.");
const spotBaseline = JSON.parse(await readFile(new URL("../content/paper-01-before-page10-11-repair.json", import.meta.url), "utf8")).paper;
storage.set(key, JSON.stringify(spotBaseline));
const spotMigrated = loadCuratorDraft(source);
const anchorId = 'paper-01-s-c92507a4832b';
const tailId = 'paper-01-s-11c642e44a44';
assert.equal(spotMigrated.segments.find(s => s.id === anchorId).fragments.length, 2);
assert.equal(spotMigrated.segments.find(s => s.id === tailId).excluded, true);
const editedSpot = structuredClone(spotBaseline);
editedSpot.segments.find(s => s.id === anchorId).translation.plainZh = 'preserved manual coding explanation';
storage.set(key, JSON.stringify(editedSpot));
const preservedSpot = loadCuratorDraft(source);
assert.equal(preservedSpot.segments.find(s => s.id === anchorId).translation.plainZh, 'preserved manual coding explanation');
assert.equal(preservedSpot.segments.find(s => s.id === anchorId).fragments.length, 1);
assert.equal(Boolean(preservedSpot.segments.find(s => s.id === tailId).excluded), false);
assert.ok(preservedSpot.pendingReadingUnitRepairs.includes(anchorId));
const readerText = await readFile(new URL('../lib/reader-state.ts', import.meta.url), 'utf8');
const companionText = await readFile(new URL('../lib/companion-state.ts', import.meta.url), 'utf8');
const companionCompiled = ts.transpileModule(companionText, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const companionUrl = `data:text/javascript;base64,${Buffer.from(companionCompiled).toString('base64')}`;
const { resolveReadingSegment } = await import(companionUrl);
const readerCompiled = ts.transpileModule(readerText, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText.replace('"@/lib/companion-state"', JSON.stringify(companionUrl));
const {loadReaderState,emptyReaderState,storageKey} = await import(`data:text/javascript;base64,${Buffer.from(readerCompiled).toString('base64')}`);
const oldState=emptyReaderState(spotBaseline);oldState.currentSegmentId=tailId;oldState.notes[tailId]='preserved continuation note';oldState.bookmarks=[tailId];
storage.set(storageKey(source.id), JSON.stringify(oldState));
const resumed=loadReaderState(source);
assert.equal(resumed.currentSegmentId,anchorId);
assert.equal(resumed.notes[tailId],'preserved continuation note');
assert.ok(resumed.bookmarks.includes(tailId));
console.log('Cross-page merge migration, manual-edit protection and archived note/bookmark preservation passed.');
const interruptionBaseline = JSON.parse(await readFile(new URL('../content/paper-01-before-interruption-repair.json', import.meta.url), 'utf8')).paper;
const groups = source.readingUnitRepairs.filter(r => r.revision === 'paper-01-exhibit-interruptions-v1');
assert.equal(groups.length, 6);
storage.set(key, JSON.stringify(interruptionBaseline));
const interruptionMigrated = loadCuratorDraft(source);
for (const group of groups) {
  assert.equal(interruptionMigrated.segments.find(s => s.id === group.targetId).fragments.length, 2);
  assert.equal(interruptionMigrated.segments.find(s => s.id === group.absorbedIds[0]).excluded, true);
  const edited = structuredClone(interruptionBaseline);
  edited.segments.find(s => s.id === group.absorbedIds[0]).translation.faithfulZh = '保留人工修改';
  storage.set(key, JSON.stringify(edited));
  const protectedDraft = loadCuratorDraft(source);
  assert.equal(protectedDraft.segments.find(s => s.id === group.targetId).fragments.length, 1);
  assert.equal(Boolean(protectedDraft.segments.find(s => s.id === group.absorbedIds[0]).excluded), false);
  assert.ok(protectedDraft.pendingReadingUnitRepairs.includes(group.targetId));
  const state = emptyReaderState(interruptionBaseline);
  state.currentSegmentId = group.absorbedIds[0];
  state.notes[state.currentSegmentId] = '原片段筆記';
  storage.set(storageKey(source.id), JSON.stringify(state));
  assert.equal(loadReaderState(source).currentSegmentId, group.targetId);
  assert.equal(loadReaderState(source).notes[group.absorbedIds[0]], '原片段筆記');
}
console.log('All six additional interruptions: old draft migration, edited-tail protection and reading-position redirects passed.');
const tableBaseline = JSON.parse(await readFile(new URL('../content/paper-01-before-complete-table-repair.json', import.meta.url), 'utf8')).paper;
const tableGroups = source.readingUnitRepairs.filter(r => r.revision === 'paper-01-complete-tables-v1');
assert.equal(tableGroups.length, 9);
storage.set(key, JSON.stringify(tableBaseline));
const tablesMigrated = loadCuratorDraft(source);
assert.equal(tablesMigrated.segments.filter(s => !s.excluded).length, source.segments.filter(s => !s.excluded).length);
for (const group of tableGroups) {
  const anchor = tablesMigrated.segments.find(s => s.id === group.targetId);
  assert.equal(anchor.kind, 'caption');
  assert.equal(anchor.sourceText, source.segments.find(s => s.id === group.targetId).sourceText);
  assert.ok(group.absorbedIds.every(id => tablesMigrated.segments.find(s => s.id === id).excluded));
  const absorbed = group.absorbedIds[0];
  const state = emptyReaderState(tableBaseline);
  state.currentSegmentId = absorbed;
  state.notes[absorbed] = '表格原筆記';
  state.bookmarks = [absorbed];
  storage.set(storageKey(source.id), JSON.stringify(state));
  const resumedTable = loadReaderState(source);
  assert.equal(resumedTable.currentSegmentId, resolveReadingSegment(source, group.targetId).id);
  assert.equal(resumedTable.notes[absorbed], '表格原筆記');
  assert.ok(resumedTable.bookmarks.includes(absorbed));
}
const editedTable = structuredClone(tableBaseline);
editedTable.segments.find(s => s.id === 'paper-01-s-937fa0a15f54').translation.faithfulZh = '保留人工表格翻譯';
storage.set(key, JSON.stringify(editedTable));
const protectedTable = loadCuratorDraft(source);
assert.equal(protectedTable.segments.find(s => s.id === 'paper-01-s-42e110a0ef05').kind, 'body');
assert.equal(Boolean(protectedTable.segments.find(s => s.id === 'paper-01-s-937fa0a15f54').excluded), false);
assert.ok(protectedTable.pendingReadingUnitRepairs.includes('paper-01-s-42e110a0ef05'));
console.log('All nine complete-table migrations, archived notes/bookmarks and manual table translation protection passed.');
